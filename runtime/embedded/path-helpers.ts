  'K.reload_modules = _dsh_reload_modules',
  'def _dsh_runtime_modules_status():',
  '    """对账已注入 runtime.py 模块：加载时的文件指纹 vs 当前磁盘指纹。"""',
  '    import os as _os, hashlib as _hl',
  '    recs = getattr(K, "runtime_module_fps", None) or {}',
  '    rows = {}',
  '    loaded = []',
  '    disk = []',
  '    for _key in sorted(recs):',
  '        _rec = recs.get(_key) or {}',
  '        _root = str(_rec.get("root") or "")',
  '        _cur = []',
  '        for _item in (_rec.get("files") or []):',
  '            _rel = str(_item.get("path") or "")',
  '            try:',
  '                _st = _os.stat(_os.path.join(_root, _rel))',
  '                with open(_os.path.join(_root, _rel), "rb") as _fh:',
  '                    _fhash = _hl.sha256(_fh.read()).hexdigest()[:12]',
  '                _cur.append("%s:%d:%s" % (_rel, _st.st_size, _fhash))',
  '            except Exception:',
  '                _cur.append(_rel + ":missing")',
  '        _dfp = "|".join(sorted(_cur))',
  '        _lfp = str(_rec.get("fp") or "")',
  '        rows[_key] = {"loaded_fp": _lfp, "disk_fp": _dfp,',
  '                      "verdict": "current" if _lfp == _dfp else "stale",',
  '                      "loaded_at": _rec.get("loaded_at")}',
  '        loaded.append(_key + "=" + _lfp)',
  '        disk.append(_key + "=" + _dfp)',
  '    def _h(_xs):',
  '        return _hl.sha256("|".join(sorted(_xs)).encode("utf-8")).hexdigest()[:12]',
  '    _count = len(rows)',
  '    return {"modules": rows,',
  '            "loaded_hash": _h(loaded),',
  '            "disk_hash": _h(disk),',
  '            "verdict": ("unknown" if _count == 0 else ("current" if _h(loaded) == _h(disk) else "stale")),',
  '            "count": _count,',
  '            "loaded_at": getattr(K, "runtime_modules_loaded_at", None)}',
  'K.runtime_modules_status = _dsh_runtime_modules_status',
  'K.out_dir = __OUTDIR__',
  '# v0.8.8：runtime 目录也注入（qc.py 据此现场加载同目录模块，如 qc_render.py）',
