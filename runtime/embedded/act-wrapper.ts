/**
 * blender_py act wrapper: runs the caller script and reports partial stdout/stderr/
 * traceback plus scene deltas and the write-scope guard (moved out of paths.ts to stay
 * inside the 600-line file budget).
 */
/** act 包装：异常也回传 partial stdout/stderr/traceback（v0.7.0） */
const ACT_HELPERS = [
  'def _dsh_epoch():',
  '    import bpy as _b',
  '    try:',
  '        h = 0',
  '        for _o in _b.data.objects:',
  '            for _c in _o.name:',
  '                h = (h * 131 + ord(_c)) & 4294967295',
  '            if _o.type == "MESH" and getattr(_o, "data", None) is not None:',
  '                h = (h * 131 + len(_o.data.vertices)) & 4294967295',
  '        return {"objects": len(_b.data.objects), "meshes": len(_b.data.meshes),',
  '                "materials": len(_b.data.materials), "nameHash": h}',
  '    except Exception as _e:',
  '        return {"error": str(_e)[:60]}',
  'def _dsh_kit():',
  '    try:',
  '        _k = globals().get("K")',
  '        return getattr(_k, "dsh_kit", None)',
  '    except Exception:',
  '        return None',
  'def _dsh_state():',
  '    try:',
  '        _kit = _dsh_kit()',
  '        if _kit is not None and hasattr(_kit, "state_probe"):',
  '            return _kit.state_probe()',
  '    except Exception as _e:',
  '        return {"error": str(_e)[:80]}',
  '    return None',
  'def _dsh_delta_of(_b, _a):',
  '    try:',
  '        _kit = _dsh_kit()',
  '        if _kit is not None and hasattr(_kit, "state_delta"):',
  '            return _kit.state_delta(_b, _a)',
  '    except Exception:',
  '        pass',
  '    return {"changed": None}',
  'def _dsh_scan(_out, _err, _src):',
  '    _body = (_out or "") + "\\n" + (_err or "")',
  '    _cancelled = sum(1 for _l in (_out or "").splitlines() if "CANCELLED" in _l)',
  '    _warn = [_l.strip() for _l in _body.splitlines()',
  '             if ("Warning:" in _l or "failed to solve" in _l.lower())][:5]',
  '    return {"cancelled_ops": _cancelled, "warnings": _warn,',
  '            "has_ops": bool(_dsh_re.search("bpy\\\\.ops\\\\.[A-Za-z0-9_.]+\\\\s*\\\\(", _src or "")),',
  '            "mutating_ops": bool(_dsh_re.search("bpy\\\\.ops\\\\.(?:mesh\\\\.(?:bevel|loopcut_slide|bisect|knife_tool|subdivide|extrude|inset|bridge_edge_loops|spin|screw|merge|delete|duplicate)|uv\\\\.(?:unwrap|smart_project|pack)|object\\\\.(?:join|separate))\\\\s*\\\\(", _src or "")),',
  '            "uv_failed": any("failed to solve" in _w.lower() or "unwrap failed" in _w.lower() for _w in _warn)}',
  'def _dsh_mode():',
  '    try:',
  '        import bpy as _b',
  '        return str(getattr(_b.context, "mode", "") or "")',
  '    except Exception:',
  '        return ""',
  'def _dsh_scope_covers(_scope, _name, _cols):',
  '    for _it in (_scope or []):',
  '        _k = str(_it.get("kind") or "")',
  '        _v = str(_it.get("value") or "")',
  '        if _k == "exclusive":',
  '            return True',
  '        if _k == "object" and _name == _v:',
  '            return True',
  '        if _k == "prefix" and _v and _name.startswith(_v):',
  '            return True',
  '        if _k == "collection" and _v and _v in (_cols or []):',
  '            return True',
  '    return False',
  'def _dsh_scope_guard(_before, _after):',
  '    _scope = globals().get("_dsh_write_scope") or []',
  '    if not _scope or any(str(_x.get("kind")) == "exclusive" for _x in _scope):',
  '        return {}',
  '    _bs = (_before or {}).get("sigs") or {}',
  '    _as = (_after or {}).get("sigs") or {}',
  '    _cols = (_after or {}).get("object_collections") or (_before or {}).get("object_collections") or {}',
  '    _changed = [n for n in set(_bs) | set(_as) if _bs.get(n) != _as.get(n)]',
  '    _outside = [n for n in _changed if not _dsh_scope_covers(_scope, n, _cols.get(n) or [])]',
  '    _deleted = []',
  '    _unrolled = []',
  '    _purged = []',
  '    _purged_mats = []',
  '    _before_meshes = globals().get("_dsh_before_meshes") or set()',
  '    _before_materials = globals().get("_dsh_before_materials") or set()',
  '    if _outside:',
  '        try:',
  '            import bpy as _b',
  '        except Exception:',
  '            _b = None',
  '        for _n in _outside:',
  '            if _n in _bs:',
  '                _unrolled.append(_n)',
  '                continue',
  '            _o = _b.data.objects.get(_n) if _b is not None else None',
  '            if _o is None:',
  '                continue',
  '            _m = getattr(_o, "data", None) if str(getattr(_o, "type", "")) == "MESH" else None',
  '            _mname = str(getattr(_m, "name", "") or "")',
  '            _mats = [s.material for s in getattr(_o, "material_slots", []) if s.material is not None]',
  '            try:',
  '                _b.data.objects.remove(_o, do_unlink=True)',
  '                _deleted.append(_n)',
  '                if _m is not None and _mname and _mname not in _before_meshes and int(getattr(_m, "users", 0) or 0) == 0:',
  '                    _b.data.meshes.remove(_m); _purged.append(_mname)',
  '                for _mat in _mats:',
  '                    _mn = str(getattr(_mat, "name", "") or "")',
  '                    if _mn and _mn not in _before_materials and int(getattr(_mat, "users", 0) or 0) == 0:',
  '                        _b.data.materials.remove(_mat); _purged_mats.append(_mn)',
  '            except Exception:',
  '                _unrolled.append(_n)',
  '    return {"scope_violations": _outside, "rolled_back": _deleted, "unrolled": _unrolled,',
  '            "purged_meshes": _purged, "purged_materials": _purged_mats,',
  '            "rollback_complete": not _unrolled}',
  'def _dsh_report():',
  '    _after0 = _dsh_state()',
  '    _scope_info = _dsh_scope_guard(_dsh_before, _after0)',
  '    _after = _dsh_state() if _scope_info.get("rolled_back") else _after0',
  '    _delta = _dsh_delta_of(_dsh_before, _after)',
  '    _diag = _dsh_scan(_dsh_o.getvalue(), _dsh_e.getvalue(), _dsh_src)',
  '    _diag["mode"] = _dsh_mode()',
  '    if _scope_info:',
  '        _diag.update(_scope_info)',
  '    _diag["no_effect"] = bool(_diag.get("mutating_ops") and _delta.get("changed") is False',
  '                              and int(_diag.get("cancelled_ops") or 0) == 0',
  '                              and not _diag.get("uv_failed"))',
  '    _diag["no_scene_change"] = bool(_delta.get("changed") is False',
  '                                   and int(_diag.get("cancelled_ops") or 0) == 0',
  '                                   and not _diag.get("uv_failed"))',
  '    return _delta, _diag',
].join(String.fromCharCode(10))

export const ACT_WRAPPER = (src: string): string =>
  [
    'import io as _dsh_io, contextlib as _dsh_ctx, traceback as _dsh_tb, json as _dsh_json, re as _dsh_re',
    '_dsh_src = _dsh_json.loads(' + JSON.stringify(JSON.stringify(src)) + ')',
    '_dsh_o = _dsh_io.StringIO(); _dsh_e = _dsh_io.StringIO()',
    ACT_HELPERS,
    'try:',
    '    import bpy as _dsh_bpy',
    '    _dsh_before_meshes = set(_dsh_bpy.data.meshes.keys())',
    '    _dsh_before_materials = set(_dsh_bpy.data.materials.keys())',
    'except Exception:',
    '    _dsh_before_meshes = set()',
    '    _dsh_before_materials = set()',
    '_dsh_before = _dsh_state()',
    'try:',
    '    with _dsh_ctx.redirect_stdout(_dsh_o), _dsh_ctx.redirect_stderr(_dsh_e):',
    '        exec(compile(_dsh_src, "<blender_py>", "exec"), globals())',
    'except BaseException as _dsh_exc:',
    '    _dsh_delta, _dsh_diag = _dsh_report()',
    '    print("DSH_ACT_ERR " + _dsh_json.dumps({"error": "%s: %s" % (type(_dsh_exc).__name__, _dsh_exc), "traceback": _dsh_tb.format_exc()[-6000:], "stdout": _dsh_o.getvalue()[-16000:], "stderr": _dsh_e.getvalue()[-8000:], "epoch": _dsh_epoch(), "changed": _dsh_delta.get("changed"), "faces_delta": _dsh_delta.get("faces_delta"), "verts_delta": _dsh_delta.get("verts_delta"), "objects_delta": _dsh_delta.get("objects_delta"), "faces_before": _dsh_delta.get("faces_before"), "faces_after": _dsh_delta.get("faces_after"), "changed_objects": _dsh_delta.get("changed_objects") or [], "changed_object_collections": _dsh_delta.get("changed_object_collections") or {}, "materials_changed": _dsh_delta.get("materials_changed") or [], "edit_mode": _dsh_delta.get("edit_mode") or [], "diagnostics": _dsh_diag}, ensure_ascii=False))',
    'else:',
    '    _dsh_delta, _dsh_diag = _dsh_report()',
    '    print("DSH_ACT_OK " + _dsh_json.dumps({"stdout": _dsh_o.getvalue()[-16000:], "stderr": _dsh_e.getvalue()[-8000:], "epoch": _dsh_epoch(), "changed": _dsh_delta.get("changed"), "faces_delta": _dsh_delta.get("faces_delta"), "verts_delta": _dsh_delta.get("verts_delta"), "objects_delta": _dsh_delta.get("objects_delta"), "faces_before": _dsh_delta.get("faces_before"), "faces_after": _dsh_delta.get("faces_after"), "changed_objects": _dsh_delta.get("changed_objects") or [], "changed_object_collections": _dsh_delta.get("changed_object_collections") or {}, "materials_changed": _dsh_delta.get("materials_changed") or [], "edit_mode": _dsh_delta.get("edit_mode") or [], "diagnostics": _dsh_diag}, ensure_ascii=False))',
    '',
  ].join(String.fromCharCode(10))
