#!/usr/bin/env node
// @ts-check
/**
 * scripts/gen-local-ops.mjs — generate the no-GUI local-lane allow-list from config/local-ops.json .
 *
 * config/local-ops.json is the single source of truth for "which op may run headless with an
 * explicit args.file". Nothing else may hand-write that list. This script renders two constant
 * modules, one per compile target:
 *   - runtime/contracts/local-lane.ts (backend contract layer: catalog + local-op table read it)
 *   - src/contracts/local-lane.ts     (host copy: src/tools/op/local.ts reads it)
 *
 * Why two files for one list: runtime/** and src/** belong to two separate tsc projects
 * (tsconfig.runtime.json / tsconfig.json), so each layer needs its own module in its own rootDir.
 * Both files are byte-identical apart from the header note, and both carry the sha256 of the
 * source plus the regeneration command. node scripts/check-local-ops.mjs (npm run check:local-ops,
 * also part of npm run lint) fails when either file is stale or was hand-edited.
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as prettier from 'prettier'

const HERE = path.dirname(fileURLToPath(import.meta.url))
export const DEFAULT_ROOT = path.resolve(HERE, '..')
export const CONFIG_FILE = 'config/local-ops.json'
export const GENERATED_FILES = ['runtime/contracts/local-lane.ts', 'src/contracts/local-lane.ts']

const fail = (message) => {
  console.error('gen-local-ops: ' + message)
  process.exit(1)
}

const isNonEmptyString = (value) => typeof value === 'string' && value.length > 0
const hasSpace = (value) => /\s/.test(value)

/** 名字表只能有两类条目：精确 op 名与非空前缀。 */
export function validateLocalOps(config) {
  const failures = []
  if (!config || typeof config !== 'object' || Array.isArray(config))
    return ['top-level value must be an object']
  if (config.version !== 1) failures.push('version must be 1')
  const list = (key) => {
    const value = config[key]
    if (!Array.isArray(value)) {
      failures.push(key + ' must be an array')
      return []
    }
    if (value.length === 0) failures.push(key + ' must be a non-empty array')
    const seen = new Set()
    value.forEach((entry, index) => {
      const at = key + '[' + index + ']'
      if (!isNonEmptyString(entry)) {
        failures.push(at + ' must be a non-empty string')
        return
      }
      if (hasSpace(entry)) failures.push(at + ' must not contain whitespace')
      const name = entry.trim()
      if (seen.has(name)) failures.push(at + ' duplicates ' + name)
      seen.add(name)
    })
    return value
  }
  list('ops')
  list('prefixes')
  return failures
}

function header(hash) {
  return [
    '// AUTO-GENERATED FILE — generated by scripts/gen-local-ops.mjs; do not edit.',
    '// Source: config/local-ops.json',
    '// Regenerate: node scripts/gen-local-ops.mjs',
    '// source-sha256: ' + hash,
  ].join('\n')
}

/** 每个落点一句"谁消费它"，其余内容逐字相同。 */
const ROLE_NOTE = {
  'runtime/contracts/local-lane.ts': [
    '//',
    '// 契约层（后端）：判定"这个 op 能否 headless"的唯一定义。catalog（runtime/foundation/output/render.ts）',
    '// 与车道表（runtime/execution/local-op/table.ts）都从这里取名字，执行层因此不必 import core/。',
  ].join('\n'),
  'src/contracts/local-lane.ts': [
    '//',
    '// 契约层（宿主副本）：src/tools/op/local.ts 的车道闸门从这里取名字。宿主包与后端包是两个',
    '// tsc 工程，同一份名单生成两次；两份内容逐字同源（config/local-ops.json），不许各自手写。',
  ].join('\n'),
}

function renderLocalLane(config, hash, file) {
  const ops = config.ops.map((op) => '  ' + JSON.stringify(op) + ',')
  return [
    header(hash),
    ROLE_NOTE[file],
    '',
    '/** 无 GUI 本地车道的名字白名单（精确 op 名，来自 config/local-ops.json）。 */',
    'export const LOCAL_OP_NAMES: readonly string[] = [',
    ...ops,
    ']',
    '',
    '/** img_ 全族共用同一条车道（同一路由行、同一 preload 模块）。 */',
    'export const LOCAL_OP_PREFIXES: readonly string[] = [' +
      config.prefixes.map((prefix) => JSON.stringify(prefix)).join(', ') +
      ']',
    '',
    '/** 只做名字判定：是否属于本地无头车道的白名单。 */',
    'export function isLocalOpName(op: unknown): boolean {',
    "  const name = String(op === undefined || op === null ? '' : op).trim()",
    '  if (!name) return false',
    '  if (LOCAL_OP_NAMES.includes(name)) return true',
    '  return LOCAL_OP_PREFIXES.some((prefix) => name.startsWith(prefix))',
    '}',
  ].join('\n')
}

async function prettierOptions(root) {
  const configPath = path.join(root, '.prettierrc.json')
  try {
    return JSON.parse(fs.readFileSync(configPath, 'utf8'))
  } catch {
    return {}
  }
}

export async function generateLocalOps(root = DEFAULT_ROOT) {
  const sourcePath = path.join(root, CONFIG_FILE)
  let source
  try {
    source = fs.readFileSync(sourcePath, 'utf8')
  } catch (error) {
    throw new Error(
      'cannot read ' + CONFIG_FILE + ': ' + String(error && error.message ? error.message : error),
      { cause: error },
    )
  }
  let config
  try {
    config = JSON.parse(source)
  } catch (error) {
    throw new Error(
      CONFIG_FILE + ' is not valid JSON: ' + String(error && error.message ? error.message : error),
      { cause: error },
    )
  }
  const failures = validateLocalOps(config)
  if (failures.length) throw new Error(CONFIG_FILE + ' is invalid:\n- ' + failures.join('\n- '))
  const hash = crypto.createHash('sha256').update(source).digest('hex')
  const options = await prettierOptions(root)
  const files = []
  for (const file of GENERATED_FILES) {
    const filePath = path.join(root, file)
    const content = await prettier.format(renderLocalLane(config, hash, file), {
      ...options,
      parser: 'typescript',
      filepath: filePath,
    })
    files.push({ file, content })
  }
  return { hash, ops: config.ops.length, prefixes: config.prefixes.length, files }
}

async function main() {
  try {
    const generated = await generateLocalOps(DEFAULT_ROOT)
    for (const file of generated.files) {
      const target = path.join(DEFAULT_ROOT, file.file)
      fs.mkdirSync(path.dirname(target), { recursive: true })
      fs.writeFileSync(target, file.content, 'utf8')
      console.log('gen-local-ops: wrote ' + file.file)
    }
    console.log(
      'gen-local-ops: OK · ' +
        generated.ops +
        ' ops · ' +
        generated.prefixes +
        ' prefixes · sha256 ' +
        generated.hash.slice(0, 12),
    )
  } catch (error) {
    fail(String(error && error.message ? error.message : error))
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main()
}
